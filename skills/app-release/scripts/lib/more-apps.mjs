// more-apps.mjs
// The shared catalogue behind the `more-apps` standard (references/standards.md, More apps): which of the owner's apps
// each app lists, read from the app sites repository (astrojams1/app-sites), and the generated Swift or TypeScript list
// an app bundles. Pure functions here; scripts/more-apps.mjs reads the repository and writes the files, and the
// standards audit (lib/standards.mjs) compares an app's bundled list with what the catalogue says today.

import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';

export const APP_SITES_ROOT = process.env.APP_SITES_ROOT || '/Volumes/ssd/code/app-sites';
const sitesRoot = () => process.env.APP_SITES_ROOT || '/Volumes/ssd/code/app-sites';
export const SITES = ['ouro', 'astrojams'];
// Products the owner took out of marketing (World Sim, 2026-11-13; the others the same week): never listed, whatever
// a profile's stage says.
export const NEVER_LISTED = ['world-sim', 'clawgree', 'eggaduppa', 'universe-of-sound'];
// Not `app-standard: more-apps`, which marks the shared file: the generated list is found by its own marker.
export const CATALOG_MARKER = 'app-standard catalogue: more-apps';

// expectedApps: every app to list, in order (the profile's weight, then name), before leaving out the app itself.
// An app is listed when its site catalogue has it, Apple's lookup (the site's store.json) shows it available, its
// marketing profile is `live`, it ships on the App Store (no `platform: web`) and the owner has not taken it out.
export function expectedApps({ profiles, sites }) {
  const out = [];
  for (const site of SITES) {
    const data = sites[site];
    if (!data) continue;
    for (const entry of data.apps.apps || []) {
      const store = entry.appStoreId && data.store.apps && data.store.apps[entry.appStoreId];
      if (!store || store.status !== 'available') continue;
      const profile = profiles.find(p => p.site === site && (p.siteSlug || p.id) === entry.slug);
      if (!profile || profile.stage !== 'live' || profile.platform === 'web' || NEVER_LISTED.includes(profile.id)) continue;
      out.push({
        id: profile.id, site, slug: entry.slug, name: entry.name, subtitle: entry.subtitle,
        appStoreId: String(entry.appStoreId), bundleId: entry.bundleId || profile.bundleId || '',
        weight: Number(profile.weight) || 0, icon: entry.icon || null
      });
    }
  }
  return out.sort((a, b) => b.weight - a.weight || a.name.localeCompare(b.name));
}

// listFor: the apps one app shows: everything expected except itself (by bundle id or App Store id).
export function listFor(apps, self = {}) {
  return apps.filter(app => app.bundleId !== self.bundleId && app.appStoreId !== String(self.appStoreId || ''));
}

const swiftString = value => JSON.stringify(String(value));

// header: the lines the audit reads back from a generated file.
export function header(apps, { generated, source }) {
  return [
    '// ' + CATALOG_MARKER,
    '// Generated by the app-release skill (scripts/more-apps.mjs) from ' + source + '. Do not edit: run it again.',
    '// generated: ' + generated,
    '// apps: ' + apps.map(app => app.id).join(',')
  ];
}

export function renderSwift(apps, meta) {
  const rows = apps.map(app => '        MoreApps.App(id: ' + swiftString(app.id) + ', name: ' + swiftString(app.name) + ', subtitle: ' + swiftString(app.subtitle)
    + ', appStoreId: ' + swiftString(app.appStoreId) + ', bundleId: ' + swiftString(app.bundleId) + ',\n                     iconJPEGBase64: ' + swiftString(app.iconBase64 || '') + ')');
  return header(apps, meta).concat(['', 'extension MoreApps {', '    static let generated = ' + swiftString(meta.generated), '    static let catalog: [MoreApps.App] = [',
    rows.join(',\n'), '    ]', '}', '']).join('\n');
}

export function renderTs(apps, meta) {
  const rows = apps.map(app => '  { id: ' + JSON.stringify(app.id) + ', name: ' + JSON.stringify(app.name) + ', subtitle: ' + JSON.stringify(app.subtitle)
    + ', appStoreId: ' + JSON.stringify(app.appStoreId) + ', bundleId: ' + JSON.stringify(app.bundleId) + ',\n    iconJPEGBase64: ' + JSON.stringify(app.iconBase64 || '') + ' }');
  return header(apps, meta).concat(['',
    'export type MoreApp = { id: string; name: string; subtitle: string; appStoreId: string; bundleId: string; iconJPEGBase64: string };', '',
    'export const MORE_APPS_GENERATED = ' + JSON.stringify(meta.generated) + ';', '',
    'export const MORE_APPS: MoreApp[] = [', rows.join(',\n'), '];', '']).join('\n');
}

// parseGenerated reads the header of a generated file: { generated, ids } or null.
export function parseGenerated(text) {
  if (!text.includes(CATALOG_MARKER)) return null;
  const generated = (text.match(/^\/\/ generated: (\d{4}-\d{2}-\d{2})/m) || [])[1] || null;
  const line = (text.match(/^\/\/ apps: (.*)$/m) || [])[1];
  return { generated, ids: line === undefined ? null : line.split(',').map(id => id.trim()).filter(Boolean) };
}

function gitShow(root, path, encoding = 'utf8') {
  const result = spawnSync('git', ['-C', root, 'show', 'origin/main:' + path], { encoding, maxBuffer: 64 * 1024 * 1024, env: { ...process.env, GIT_OPTIONAL_LOCKS: '0' } });
  return result.status === 0 ? result.stdout : null;
}

// readCatalogue reads the profiles and both sites' catalogues from the app sites repository's origin/main, so a
// checkout on another branch or with local edits never leaks into an app. Returns null when it cannot be read.
const read = new Map();
export function readCatalogue(root = sitesRoot()) {
  if (!read.has(root)) read.set(root, readCatalogueOnce(root));
  return read.get(root);
}

function readCatalogueOnce(root) {
  if (!existsSync(root)) return null;
  const list = spawnSync('git', ['-C', root, 'ls-tree', '--name-only', 'origin/main', 'marketing/apps/'], { encoding: 'utf8', env: { ...process.env, GIT_OPTIONAL_LOCKS: '0' } });
  if (list.status !== 0) return null;
  const profiles = list.stdout.split('\n').filter(path => path.endsWith('.json')).map(path => JSON.parse(gitShow(root, path)));
  const sites = {};
  for (const site of SITES) {
    const apps = gitShow(root, 'sites/' + site + '/src/data/apps.json');
    const store = gitShow(root, 'sites/' + site + '/src/data/store.json');
    if (apps && store) sites[site] = { apps: JSON.parse(apps), store: JSON.parse(store) };
  }
  const commit = (spawnSync('git', ['-C', root, 'rev-parse', '--short', 'origin/main'], { encoding: 'utf8' }).stdout || '').trim();
  return { profiles, sites, commit, root, gitShow: (path, encoding) => gitShow(root, path, encoding) };
}
